// Writes the site's types from S4's JSON Schema (S5 spec §17.3: the site's types are generated
// from the schema the export is checked against): src/lib/board-index-types.ts for index.json
// and src/lib/board-case-types.ts for a case file. `--check` fails if either file is stale.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";
import { format, resolveConfig } from "prettier";

const schema = JSON.parse(readFileSync("../docs/schemas/board-1.schema.json", "utf8"));

// A property's own `title` would become a type alias of its own (TookDays, CaseNumber, ...);
// only the named definitions under $defs, and the root, keep theirs.
function stripPropertyTitles(node, keep) {
    if (Array.isArray(node)) return node.map((n) => stripPropertyTitles(n, false));
    if (node === null || typeof node !== "object") return node;
    const out = {};
    for (const [key, value] of Object.entries(node)) {
        if (key === "title" && !keep) continue;
        if (key === "$defs") {
            out[key] = Object.fromEntries(
                Object.entries(value).map(([n, d]) => [n, stripPropertyTitles(d, true)]),
            );
        } else {
            out[key] = stripPropertyTitles(value, false);
        }
    }
    return out;
}

const banner =
    "// Generated by scripts/gen-types.mjs from docs/schemas/board-1.schema.json. Do not edit.\n";
let stale = false;
for (const [key, path] of [
    ["index", "src/lib/board-index-types.ts"],
    ["case", "src/lib/board-case-types.ts"],
]) {
    const ts = await compile(stripPropertyTitles(schema[key], true), key, {
        bannerComment: "",
        additionalProperties: false,
        strictIndexSignatures: true,
    });
    const out = await format(banner + ts, {
        ...(await resolveConfig(path, { editorconfig: true })),
        filepath: path,
    });
    if (process.argv.includes("--check")) {
        const current = existsSync(path) ? readFileSync(path, "utf8") : "";
        if (current !== out) {
            console.error(`${path} is stale: run pnpm run types`);
            stale = true;
        }
    } else {
        writeFileSync(path, out);
    }
}
if (stale) process.exit(1);
